"""Write results/primary/summary.md from the csv files in results/primary/.

Every number in the summary is read from those files. After writing, the
summary is checked: each number in it must round from a value in one of the
csv files, at the precision it is written with. The summary reports numbers
only, with no interpretation.

Run from the project root: .venv/bin/python src/summarize_primary.py
"""

import re
import sys

import numpy as np
import pandas as pd

from primary_analysis import OUT_DIR, PRIMARY_WINDOW, ROOT, STANDALONE_SOURCES

SUMMARY = OUT_DIR / "summary.md"

# a number as written in the summary: optional minus, thousands commas,
# decimals, exponent. digits that are part of a word (r2, dim_20_100) are not
# numbers.
NUMBER = re.compile(r"(?<![\w.])-?\d+(?:,\d{3})*(?:\.\d+)?(?:[eE][-+]?\d+)?(?!\w)")


def unmatched_numbers(text, csv_paths, ignore=()):
    """Numbers in text that do not round from any numeric value in the csv files.

    A number written with d decimals (or d mantissa decimals in e-notation)
    matches a value within half a unit of its last digit. Labels in ignore
    (source names such as "2004 FSA") are removed before looking for numbers.
    """
    for label in ignore:
        text = text.replace(label, " ")
    values = np.concatenate(
        [pd.read_csv(path).select_dtypes("number").to_numpy(dtype=float).ravel() for path in csv_paths]
    )
    values = values[np.isfinite(values)]
    unmatched = []
    for token in NUMBER.findall(text):
        number = token.replace(",", "")
        mantissa, _, exponent = number.lower().partition("e")
        decimals = len(mantissa.partition(".")[2])
        half_unit = 0.5 * 10.0 ** (int(exponent or 0) - decimals)
        if not np.any(np.abs(values - float(number)) <= half_unit * (1 + 1e-9)):
            unmatched.append(token)
    return unmatched


def read(name):
    return pd.read_csv(OUT_DIR / name)


def f4(value):
    return f"{value:.4f}"


def p(value):
    return f"{value:.3g}"


def count(value):
    return f"{int(value):,}"


def window_label(min_m, max_m):
    return f"{min_m:g}–{max_m:g} m"


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def rho_section(frame, ci_label):
    rows = []
    for r in frame.itertuples():
        window = window_label(r.window_min_m, r.window_max_m)
        if r.window == PRIMARY_WINDOW:
            window += " (primary)"
        rows.append([window, r.measure, count(r.n), f4(r.rho), p(r.p_value), f"[{f4(r.ci_low)}, {f4(r.ci_high)}]"])
    return table(["window", "measure", "n", "rho", "p", ci_label], rows)


def runtime_rows(frame):
    return [
        [r.run, count(r.n_lakes), count(r.workers), f"{r.median_s:.2f}", f"{r.max_s:.2f}",
         str(int(r.slowest_objectid)), f"{r.wall_s:.1f}"]
        for r in frame.itertuples()
    ]


def main():
    params = read("parameters.csv").set_index("parameter")["value"]
    ci_label = f"{params['ci_level_percent']:g}% CI"
    threshold = f"{params['r2_threshold']:g}"
    rho = read("rho_primary.csv")
    windows = rho.drop_duplicates("window").set_index("window")
    rule = read("decision_rule.csv")
    fit = read("r2_below_threshold.csv")
    groups = read("source_groups.csv")
    kw = read("kruskal_wallis.csv").iloc[0]
    explore_fit = read("exploratory_10acre_r2_below_threshold.csv").iloc[0]

    sections = [
        "# Primary analysis: results",
        "Protocol: the pre-registered design in CLAUDE.md. Generated by src/summarize_primary.py from the csv "
        "files in results/primary/, named under each heading. Numbers are rounded from those files.",
        "## Samples (sample_log.csv)",
        table(["sample", "n"], [[r.sample, count(r.n)] for r in read("sample_log.csv").itertuples()]),
        "## Parameters (parameters.csv)",
        table(["parameter", "value"], [[name, f"{value:g}"] for name, value in params.items()]),
        "## Spearman rho, primary sample (rho_primary.csv)",
        rho_section(rho, ci_label),
        "## Decision rule (decision_rule.csv)",
        "Applied separately to area and to shoreline length: supported only if rho has the same sign in all "
        "three windows. p-values and confidence intervals are not part of the rule.",
        table(
            ["measure"]
            + [f"rho {window_label(w.window_min_m, w.window_max_m)}" for w in windows.itertuples()]
            + ["direction", "same sign in all windows", "outcome"],
            [
                [r["measure"]]
                + [f4(r[f"rho_{w}"]) for w in windows.index]
                + [r["direction"], "yes" if r["direction_holds"] else "no", r["outcome"]]
                for _, r in rule.iterrows()
            ],
        ),
        f"## Fit quality: lakes with r2 below {threshold} (r2_below_threshold.csv)",
        table(
            ["window", "lakes", f"r2 < {threshold}", "min r2"],
            [
                [window_label(r.window_min_m, r.window_max_m), count(r.n_lakes), count(r.n_r2_below), f4(r.min_r2)]
                for r in fit.itertuples()
            ],
        ),
        "## Mapping source comparison, primary window (source_groups.csv, kruskal_wallis.csv)",
        "Lakes with a missing delineat_1 are excluded from this comparison only.",
        table(
            ["group", "n", f"median dimension, {window_label(windows.loc[PRIMARY_WINDOW, 'window_min_m'], windows.loc[PRIMARY_WINDOW, 'window_max_m'])}"],
            [[r.group, count(r.n), f4(r.median_dim)] for r in groups.itertuples()],
        ),
        table(
            ["test", "H", "p", "groups", "lakes", "excluded (missing delineat_1)"],
            [["kruskal-wallis", f"{kw['H']:.2f}", p(kw["p_value"]), count(kw["n_groups"]), count(kw["n_lakes"]),
              count(kw["n_excluded_missing"])]],
        ),
        "## Within-source check: 2004 FSA only (rho_within_2004_fsa.csv)",
        "Reported alongside the decision rule, not part of it.",
        rho_section(read("rho_within_2004_fsa.csv"), ci_label),
        "## Sensitivity: pilot lakes excluded (rho_sensitivity_no_pilot.csv)",
        rho_section(read("rho_sensitivity_no_pilot.csv"), ci_label),
        "## Exploratory: 10-acre sample, primary window only (exploratory_10acre_rho.csv, "
        "exploratory_10acre_r2_below_threshold.csv)",
        "Exploratory. No decision rule is applied.",
        rho_section(read("exploratory_10acre_rho.csv"), ci_label),
        table(
            ["lakes", f"r2 < {threshold}", "min r2"],
            [[count(explore_fit["n_lakes"]), count(explore_fit["n_r2_below"]), f4(explore_fit["min_r2"])]],
        ),
        "## Runtime (runtime.csv, exploratory_10acre_runtime.csv)",
        "Seconds per lake, all windows of the run together.",
        table(
            ["run", "lakes", "workers", "median s", "max s", "slowest objectid", "wall s"],
            runtime_rows(read("runtime.csv")) + runtime_rows(read("exploratory_10acre_runtime.csv")),
        ),
        "## Notes",
        "- The design was informed by the pilot results (results/pilot/). The methods must state this.\n"
        "- Confidence intervals are percentile bootstrap intervals: lakes resampled with replacement, the same "
        "resamples for every rho within a sample.\n"
        "- Area is the DNR acres attribute. Shoreline length is shoreline_m from src/filter_lakes.py.",
    ]
    text = "\n\n".join(sections) + "\n"
    SUMMARY.write_text(text)

    csvs = sorted(OUT_DIR.glob("*.csv"))
    missing = unmatched_numbers(text, csvs, ignore=STANDALONE_SOURCES)
    if missing:
        sys.exit(f"numbers in summary.md not found in results/primary/*.csv: {missing}")
    stripped = text
    for label in STANDALONE_SOURCES:
        stripped = stripped.replace(label, " ")
    print(f"wrote {SUMMARY.relative_to(ROOT)}: all {len(NUMBER.findall(stripped))} numbers found in results/primary/*.csv")


if __name__ == "__main__":
    main()
